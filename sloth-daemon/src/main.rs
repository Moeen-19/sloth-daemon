/// Parses effective UID from Linux `/proc/self/status` content.
pub fn parse_euid_from_status(status_content: &str) -> Option<u32> {
    for line in status_content.lines() {
        if let Some(rest) = line.strip_prefix("Uid:") {
            let mut parts = rest.split_whitespace();
            let _real_uid = parts.next()?;
            let effective_uid = parts.next()?;
            return effective_uid.parse().ok();
        }
    }
    None
}

/// Returns the effective UID of the current process by reading `/proc/self/status`.
pub fn current_euid() -> Option<u32> {
    let content = fs::read_to_string("/proc/self/status").ok()?;
    parse_euid_from_status(&content)
}

/// Parses the thread group ID (TGID / process ID) from `/proc/<pid>/status`.
pub fn parse_tgid_from_status(status_content: &str) -> Option<u32> {
    for line in status_content.lines() {
        if let Some(rest) = line.strip_prefix("Tgid:") {
            return rest.trim().parse().ok();
        }
    }
    None
}

/// Resolves the process ID (TGID) for a given kernel task ID (TID).
///
/// If `/proc/<tid>/status` is unavailable (e.g. process exited), falls back to `tid`.
pub fn get_tgid(tid: u32) -> u32 {
    let path = format!("/proc/{tid}/status");
    if let Ok(content) = fs::read_to_string(&path) {
        if let Some(tgid) = parse_tgid_from_status(&content) {
            return tgid;
        }
    }
    tid
}

/// Determines whether a process is a kernel thread given process introspection signals.
pub fn is_kernel_thread_from_proc(has_exe: bool, cmdline: &str) -> bool {
    !has_exe && cmdline.trim().is_empty()
}

/// Checks whether a given PID is a kernel thread.
pub fn is_kernel_thread(pid: u32) -> bool {
    // PID 0 (idle) and PID 2 (kthreadd) are kernel threads
    if pid == 0 || pid == 2 {
        return true;
    }
    let proc_dir = format!("/proc/{pid}");
    if !Path::new(&proc_dir).exists() {
        return false;
    }
    let has_exe = fs::read_link(format!("/proc/{pid}/exe")).is_ok();
    let cmdline = fs::read_to_string(format!("/proc/{pid}/cmdline")).unwrap_or_default();
    is_kernel_thread_from_proc(has_exe, &cmdline)
}

/// Resolves the executable name for a process from `/proc/<pid>/comm` or a cached value.
pub fn resolve_comm(pid: u32, cache: &mut StdHashMap<u32, String>) -> String {
    if let Ok(comm) = fs::read_to_string(format!("/proc/{pid}/comm")) {
        let trimmed = comm.trim().to_string();
        if !trimmed.is_empty() {
            cache.insert(pid, trimmed.clone());
            return trimmed;
        }
    }
    cache
        .get(&pid)
        .cloned()
        .unwrap_or_else(|| "<exited>".to_string())
}

/// Calculates CPU usage percentage from elapsed time and on-CPU nanosecond delta.
/// 100.0 represents 100% of one core.
pub fn calculate_cpu_percent(delta_ns: u64, elapsed_ns: u64) -> f32 {
    if elapsed_ns == 0 {
        return 0.0;
    }
    (delta_ns as f32 / elapsed_ns as f32) * 100.0
}

/// Samples the `PID_CPU_NS` BPF map, aggregates thread CPU times to TGIDs, and returns
/// process samples sorted by CPU% descending.
pub fn sample_processes(
    pid_cpu_ns: &AyaHashMap<&aya::maps::MapData, u32, u64>,
    prev_totals: &mut StdHashMap<u32, u64>,
    comm_cache: &mut StdHashMap<u32, String>,
    sustained_tracker: &mut StdHashMap<u32, u32>,
    miss_counts: &mut StdHashMap<u32, u8>,
    elapsed_ns: u64,
    config: &Config,
) -> Vec<ProcessSample> {
    // 1. Read all TID entries from the kernel map
    let mut current_tid_entries = Vec::new();
    for (tid, total_ns) in pid_cpu_ns.iter().flatten() {
        current_tid_entries.push((tid, total_ns));
    }

    // 2. Aggregate thread nanoseconds into process TGID totals
    let mut current_tgid_totals: StdHashMap<u32, u64> = StdHashMap::new();
    for (tid, total_ns) in current_tid_entries {
        let tgid = get_tgid(tid);
        let entry = current_tgid_totals.entry(tgid).or_insert(0);
        *entry = entry.wrapping_add(total_ns);
    }

    // 2b. Grace period: for TGIDs in prev_totals but absent from BPF map,
    //     carry them forward for one tick if /proc/<tgid> still exists.
    let prev_tgids: Vec<u32> = prev_totals.keys().copied().collect();
    for tgid in prev_tgids {
        if let std::collections::hash_map::Entry::Vacant(e) = current_tgid_totals.entry(tgid) {
            let missed_before = *miss_counts.get(&tgid).unwrap_or(&0);
            if missed_before == 0 && Path::new(&format!("/proc/{tgid}")).exists() {
                // First miss and process still alive: carry forward prev total
                let carried = *prev_totals.get(&tgid).unwrap_or(&0);
                e.insert(carried);
                miss_counts.insert(tgid, 1);
            } else {
                // Second consecutive miss or process exited: allow prune
                miss_counts.remove(&tgid);
            }
        }
    }

    // 3. Compute CPU deltas and build ProcessSample structs
    let mut samples = Vec::new();
    for (&tgid, &current_total) in &current_tgid_totals {
        // Filter out kernel threads
        if is_kernel_thread(tgid) {
            continue;
        }

        let prev = prev_totals.get(&tgid).copied();
        let delta_ns = match prev {
            Some(p) if current_total >= p => current_total - p,
            // Counter reset or first observation: treat delta as 0
            _ => 0,
        };

        let cpu_percent = calculate_cpu_percent(delta_ns, elapsed_ns);
        let comm = resolve_comm(tgid, comm_cache);

        // Update sustained duration tracking.
        // Only reset on a REAL observation below threshold (delta_ns > 0).
        // A carried-forward tick (delta_ns == 0 from a grace-period miss) leaves sustained unchanged.
        let sustained_entry = sustained_tracker.entry(tgid).or_insert(0);
        if cpu_percent >= config.sampling.cpu_threshold_pct {
            *sustained_entry = sustained_entry.saturating_add(config.sampling.interval_secs);
            // Clear miss count since CPU is hot this tick
            miss_counts.remove(&tgid);
        } else if delta_ns > 0 {
            // Genuine low-CPU observation: reset sustained
            *sustained_entry = 0;
        }
        // else delta_ns == 0 (carried-forward grace tick): leave sustained unchanged

        samples.push(ProcessSample {
            pid: tgid,
            comm,
            cpu_percent,
            window_secs: config.sampling.interval_secs,
            sustained_secs: *sustained_entry,
        });
    }

    // 4. Update previous totals and prune dead processes
    prev_totals.retain(|tgid, _| current_tgid_totals.contains_key(tgid));
    comm_cache.retain(|tgid, _| current_tgid_totals.contains_key(tgid));
    sustained_tracker.retain(|tgid, _| current_tgid_totals.contains_key(tgid));
    for (tgid, total) in current_tgid_totals {
        prev_totals.insert(tgid, total);
    }

    // 5. Sort by cpu_percent descending
    samples.sort_by(|a, b| {
        b.cpu_percent
            .partial_cmp(&a.cpu_percent)
            .unwrap_or(std::cmp::Ordering::Equal)
    });
    samples
}

/// Formats a top-N table of busiest processes for logging.
pub fn format_top_n_table(samples: &[ProcessSample], top_n: usize) -> String {
    let mut out = String::new();
    out.push_str(&format!("\n{:-<50}\n", ""));
    out.push_str(&format!(
        "{:<8} {:<16} {:>8} {:>14}\n",
        "PID", "COMM", "CPU%", "SUSTAINED"
    ));
    out.push_str(&format!("{:-<50}\n", ""));
    for s in samples.iter().take(top_n) {
        let comm_disp = if s.comm.len() > 16 {
            &s.comm[..16]
        } else {
            &s.comm
        };
        out.push_str(&format!(
            "{:<8} {:<16} {:>7.1}% {:>13}s\n",
            s.pid, comm_disp, s.cpu_percent, s.sustained_secs
        ));
    }
    out.push_str(&format!("{:-<50}", ""));
    out
}

