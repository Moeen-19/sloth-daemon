/// Status result of an individual preflight check.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum CheckStatus {
    /// Check succeeded.
    Ok,
    /// Check failed.
    Fail,
}

/// Descriptive result of a system preflight check.
#[derive(Debug, Clone)]
pub struct PreflightResult {
    /// Name or description of the check.
    pub name: &'static str,
    /// Status result.
    pub status: CheckStatus,
    /// Detail message.
    pub message: String,
}

/// Checks whether `/proc/self/mountinfo` indicates cgroup2 mounted at `/sys/fs/cgroup`.
pub fn check_cgroup2_in_mountinfo(mountinfo: &str, target_path: &str) -> bool {
    for line in mountinfo.lines() {
        let mut parts = line.split(" - ");
        if let (Some(prefix), Some(suffix)) = (parts.next(), parts.next()) {
            let prefix_fields: Vec<&str> = prefix.split_whitespace().collect();
            let suffix_fields: Vec<&str> = suffix.split_whitespace().collect();
            // Prefix field index 4 is the mount point
            if prefix_fields.len() >= 5 && suffix_fields.len() >= 2 {
                let mount_point = prefix_fields[4];
                let fstype = suffix_fields[0];
                if mount_point == target_path && fstype == "cgroup2" {
                    return true;
                }
            }
        }
    }
    false
}

/// Executes all system preflight checks and returns their individual statuses.
pub fn run_preflight_checks() -> Vec<PreflightResult> {
    let mut results = Vec::new();

    // 1. Operating System
    if cfg!(target_os = "linux") {
        results.push(PreflightResult {
            name: "Operating system (Linux)",
            status: CheckStatus::Ok,
            message: "running on Linux".to_string(),
        });
    } else {
        results.push(PreflightResult {
            name: "Operating system (Linux)",
            status: CheckStatus::Fail,
            message: "sloth-daemon only supports Linux".to_string(),
        });
    }

    // 2. cgroup v2 mount check
    let cgroup_dir = Path::new("/sys/fs/cgroup");
    if !cgroup_dir.exists() {
        results.push(PreflightResult {
            name: "cgroup v2 hierarchy (/sys/fs/cgroup)",
            status: CheckStatus::Fail,
            message: "/sys/fs/cgroup directory does not exist".to_string(),
        });
    } else {
        match fs::read_to_string("/proc/self/mountinfo") {
            Ok(content) => {
                if check_cgroup2_in_mountinfo(&content, "/sys/fs/cgroup") {
                    results.push(PreflightResult {
                        name: "cgroup v2 hierarchy (/sys/fs/cgroup)",
                        status: CheckStatus::Ok,
                        message: "cgroup2 filesystem mounted at /sys/fs/cgroup".to_string(),
                    });
                } else {
                    results.push(PreflightResult {
                        name: "cgroup v2 hierarchy (/sys/fs/cgroup)",
                        status: CheckStatus::Fail,
                        message:
                            "cgroup v2 not found at /sys/fs/cgroup (cgroup v1 / hybrid not supported)"
                                .to_string(),
                    });
                }
            }
            Err(err) => {
                results.push(PreflightResult {
                    name: "cgroup v2 hierarchy (/sys/fs/cgroup)",
                    status: CheckStatus::Fail,
                    message: format!("failed to read /proc/self/mountinfo: {err}"),
                });
            }
        }
    }

    // 3. Kernel BTF support
    let btf_path = Path::new("/sys/kernel/btf/vmlinux");
    if btf_path.exists() {
        results.push(PreflightResult {
            name: "Kernel BTF (/sys/kernel/btf/vmlinux)",
            status: CheckStatus::Ok,
            message: "BTF debug info present".to_string(),
        });
    } else {
        results.push(PreflightResult {
            name: "Kernel BTF (/sys/kernel/btf/vmlinux)",
            status: CheckStatus::Fail,
            message: "/sys/kernel/btf/vmlinux not found (kernel lacks BTF support)".to_string(),
        });
    }

    // 4. Privileges check
    match current_euid() {
        Some(0) => {
            results.push(PreflightResult {
                name: "Process privileges (root / capabilities)",
                status: CheckStatus::Ok,
                message: "running as root (UID 0)".to_string(),
            });
        }
        Some(euid) => {
            results.push(PreflightResult {
                name: "Process privileges (root / capabilities)",
                status: CheckStatus::Fail,
                message: format!(
                    "running as non-root UID {euid}; root or CAP_BPF/CAP_SYS_RESOURCE required"
                ),
            });
        }
        None => {
            results.push(PreflightResult {
                name: "Process privileges (root / capabilities)",
                status: CheckStatus::Fail,
                message: "unable to determine process UID from /proc/self/status".to_string(),
            });
        }
    }

    // 5. Embedded eBPF object status
    match check_ebpf_object(EBPF_BYTES) {
        Ok(()) => {
            results.push(PreflightResult {
                name: "eBPF probe object",
                status: CheckStatus::Ok,
                message: "valid eBPF ELF binary embedded".to_string(),
            });
        }
        Err(EbpfError::NotBuilt) => {
            results.push(PreflightResult {
                name: "eBPF probe object",
                status: CheckStatus::Fail,
                message: "eBPF object not built (run: cargo +nightly build --package sloth-ebpf --target bpfel-unknown-none -Z build-std=core --release)".to_string(),
            });
        }
        Err(EbpfError::InvalidFormat) => {
            results.push(PreflightResult {
                name: "eBPF probe object",
                status: CheckStatus::Fail,
                message: "invalid embedded eBPF object format".to_string(),
            });
        }
    }

    results
}

/// Prints formatted preflight results and returns true if all checks passed.
pub fn print_preflight_results(results: &[PreflightResult]) -> bool {
    println!("=== Sloth Daemon Preflight Check ===");
    let mut all_ok = true;
    for r in results {
        match r.status {
            CheckStatus::Ok => {
                println!("[OK]   {}: {}", r.name, r.message);
            }
            CheckStatus::Fail => {
                println!("[FAIL] {}: {}", r.name, r.message);
                all_ok = false;
            }
        }
    }
    println!("====================================");
    if all_ok {
        println!("Result: All preflight checks passed.");
    } else {
        let fails = results
            .iter()
            .filter(|r| r.status == CheckStatus::Fail)
            .count();
        println!("Result: {fails} check(s) failed.");
    }
    all_ok
}

