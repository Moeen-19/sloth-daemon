    #[test]
    fn test_calculate_cpu_percent() {
        // 1 second of CPU in a 1 second window = 100% of 1 core
        assert_eq!(calculate_cpu_percent(1_000_000_000, 1_000_000_000), 100.0);

        // 2 seconds of CPU in a 1 second window (2 cores saturated) = 200%
        assert_eq!(calculate_cpu_percent(2_000_000_000, 1_000_000_000), 200.0);

        // 0 CPU used
        assert_eq!(calculate_cpu_percent(0, 1_000_000_000), 0.0);

        // 0 elapsed time
        assert_eq!(calculate_cpu_percent(1_000_000, 0), 0.0);
    }

    #[test]
    fn test_is_kernel_thread_from_proc() {
        // Kernel threads have no executable mapping and an empty cmdline
        assert!(is_kernel_thread_from_proc(false, ""));
        assert!(is_kernel_thread_from_proc(false, "   \n"));

        // User processes have an executable mapping
        assert!(!is_kernel_thread_from_proc(true, ""));
        assert!(!is_kernel_thread_from_proc(true, "yes\0"));

        // Process with no exe link but non-empty cmdline (e.g. unlinked binary) is not a kernel thread
        assert!(!is_kernel_thread_from_proc(false, "custom-prog"));
    }

