/// Sloth Daemon CLI options.
#[derive(Parser, Debug)]
#[command(
    name = "sloth-daemon",
    version,
    about = "AI-Assisted eBPF CPU Governor"
)]
pub struct Cli {
    /// Path to TOML configuration file
    #[arg(short, long)]
    pub config: Option<PathBuf>,

    /// Run system preflight checks and exit
    #[arg(long)]
    pub check: bool,

    /// Enable debug-level logging output (including per-interval top-N process table)
    #[arg(short, long)]
    pub debug: bool,
}

#[tokio::main]
async fn main() -> ExitCode {
    let cli = Cli::parse();

    if cli.check {
        let results = run_preflight_checks();
        let ok = print_preflight_results(&results);
        return if ok {
            ExitCode::SUCCESS
        } else {
            ExitCode::FAILURE
        };
    }

    // Initialize structured logging (debug level if requested, otherwise info)
    let default_level = if cli.debug { "debug" } else { "info" };
    tracing_subscriber::fmt()
        .with_env_filter(
            tracing_subscriber::EnvFilter::try_from_default_env()
                .unwrap_or_else(|_| tracing_subscriber::EnvFilter::new(default_level)),
        )
        .init();

    info!("Starting Sloth Daemon v{}", env!("CARGO_PKG_VERSION"));

    // Run preflight checks before running the daemon
    let preflight = run_preflight_checks();
    let preflight_ok = preflight.iter().all(|r| r.status == CheckStatus::Ok);
    if !preflight_ok {
        error!("System preflight check failed:");
        for r in preflight {
            if r.status == CheckStatus::Fail {
                error!("  - {}: {}", r.name, r.message);
            }
        }
        return ExitCode::FAILURE;
    }

    let config = match Config::load(cli.config.as_deref()) {
        Ok(cfg) => cfg,
        Err(err) => {
            error!("Configuration error: {err}");
            return ExitCode::FAILURE;
        }
    };

    info!(
        dry_run = config.dry_run,
        sample_interval = config.sampling.interval_secs,
        cpu_threshold = config.sampling.cpu_threshold_pct,
        "Configuration loaded successfully"
    );

    // Validate eBPF embedded bytes
    if let Err(err) = check_ebpf_object(EBPF_BYTES) {
        error!("Cannot initialize eBPF probe: {err}");
        return ExitCode::FAILURE;
    }

    // Load eBPF probe into the kernel
    info!("Loading eBPF kernel probe...");
    let mut bpf = match Ebpf::load(EBPF_BYTES) {
        Ok(b) => b,
        Err(err) => {
            error!("Failed to load eBPF probe: {err}");
            return ExitCode::FAILURE;
        }
    };

    // Attach sched_switch tracepoint
    let switch_prog: &mut TracePoint = match bpf.program_mut("sched_switch") {
        Some(p) => match <&mut TracePoint>::try_from(p) {
            Ok(tp) => tp,
            Err(err) => {
                error!("Failed to convert 'sched_switch' to TracePoint: {err}");
                return ExitCode::FAILURE;
            }
        },
        None => {
            error!("eBPF program 'sched_switch' not found in object");
            return ExitCode::FAILURE;
        }
    };
    if let Err(err) = switch_prog.load() {
        error!("Failed to load 'sched_switch' tracepoint program: {err}");
        return ExitCode::FAILURE;
    }
    if let Err(err) = switch_prog.attach("sched", "sched_switch") {
        error!("Failed to attach 'sched_switch' tracepoint: {err}");
        return ExitCode::FAILURE;
    }

    // Attach sched_process_exit tracepoint
    let exit_prog: &mut TracePoint = match bpf.program_mut("sched_process_exit") {
        Some(p) => match <&mut TracePoint>::try_from(p) {
            Ok(tp) => tp,
            Err(err) => {
                error!("Failed to convert 'sched_process_exit' to TracePoint: {err}");
                return ExitCode::FAILURE;
            }
        },
        None => {
            error!("eBPF program 'sched_process_exit' not found in object");
            return ExitCode::FAILURE;
        }
    };
    if let Err(err) = exit_prog.load() {
        error!("Failed to load 'sched_process_exit' tracepoint program: {err}");
        return ExitCode::FAILURE;
    }
    if let Err(err) = exit_prog.attach("sched", "sched_process_exit") {
        error!("Failed to attach 'sched_process_exit' tracepoint: {err}");
        return ExitCode::FAILURE;
    }

    info!("eBPF tracepoints attached (sched:sched_switch, sched:sched_process_exit)");

    // Access PID_CPU_NS BPF map
    let pid_map = match bpf.map("PID_CPU_NS") {
        Some(m) => m,
        None => {
            error!("BPF map 'PID_CPU_NS' not found");
            return ExitCode::FAILURE;
        }
    };
    let pid_cpu_ns = match AyaHashMap::<&aya::maps::MapData, u32, u64>::try_from(pid_map) {
        Ok(m) => m,
        Err(err) => {
            error!("Failed to access 'PID_CPU_NS' map: {err}");
            return ExitCode::FAILURE;
        }
    };

    // Initialize cgroup v2 enforcement manager
    let mut cgroup_mgr = match cgroup_manager::CgroupManager::new(&config) {
        Ok(mgr) => mgr,
        Err(err) => {
            error!("Failed to initialize cgroup manager: {err}");
            return ExitCode::FAILURE;
        }
    };

    info!(
        dry_run = config.dry_run,
        max_concurrent = config.throttle.max_concurrent,
        quota_pct = config.throttle.quota_pct,
        "Cgroup enforcement manager initialized"
    );

    // Initialize AI classifier (advisory only; failures degrade gracefully to unknown).
    let classifier = match ai_classifier::Classifier::new(&config.ai).await {
        Ok(c) => {
            // Health check at startup: warn if Ollama is missing but do not abort.
            match c.health().await {
                HealthStatus::Ready => info!(
                    model = %config.ai.model,
                    url = %config.ai.ollama_url,
                    "AI classifier: Ollama ready"
                ),
                HealthStatus::ModelMissing(ref m) => warn!(
                    model = %m,
                    url = %config.ai.ollama_url,
                    "AI classifier: model not installed (run: ollama pull {}); verdicts will be unknown",
                    m
                ),
                HealthStatus::Unreachable(ref reason) => warn!(
                    reason = %reason,
                    url = %config.ai.ollama_url,
                    "AI classifier: Ollama not reachable; verdicts will be unknown until it starts"
                ),
            }
            Arc::new(c)
        }
        Err(err) => {
            // Non-loopback URL rejection is a hard error; all other init failures are warnings.
            error!("AI classifier failed to initialize: {err}");
            return ExitCode::FAILURE;
        }
    };

    // Set up emergency panic hook to clean up cgroups on panic
    let default_hook = std::panic::take_hook();
    std::panic::set_hook(Box::new(move |info| {
        warn!("Daemon panic encountered! Performing emergency cgroup cleanup...");
        let parent =
            Path::new(cgroup_manager::DEFAULT_CGROUP_ROOT).join(cgroup_manager::DAEMON_CGROUP_NAME);
        if let Ok(entries) = fs::read_dir(&parent) {
            let root_procs = Path::new(cgroup_manager::DEFAULT_CGROUP_ROOT).join("cgroup.procs");
            for entry in entries.flatten() {
                if entry.file_name().to_string_lossy().starts_with("pid-") {
                    let procs = entry.path().join("cgroup.procs");
                    if let Ok(pids) = fs::read_to_string(&procs) {
                        for pid in pids.lines() {
                            let _ = fs::write(&root_procs, format!("{pid}\n"));
                        }
                    }
                    let _ = fs::remove_dir(entry.path());
                }
            }
        }
        default_hook(info);
    }));

    info!(
        interval_secs = config.sampling.interval_secs,
        "CPU observation probe active. Starting sampling loop..."
    );

    // Observer loop state
    let interval_duration = Duration::from_secs(config.sampling.interval_secs as u64);
    let mut interval = tokio::time::interval(interval_duration);
    interval.set_missed_tick_behavior(tokio::time::MissedTickBehavior::Skip);

    let mut prev_totals: StdHashMap<u32, u64> = StdHashMap::new();
    let mut comm_cache: StdHashMap<u32, String> = StdHashMap::new();
    let mut sustained_tracker: StdHashMap<u32, u32> = StdHashMap::new();
    let mut last_sample_time = Instant::now();

    loop {
        tokio::select! {
            _ = tokio::signal::ctrl_c() => {
                info!("Received interrupt signal (Ctrl+C). Releasing all throttled cgroups and stopping...");
                cgroup_mgr.release_all();
                break;
            }
            _ = interval.tick() => {
                let now = Instant::now();
                let elapsed_ns = now.duration_since(last_sample_time).as_nanos() as u64;
                last_sample_time = now;

                let samples = sample_processes(
                    &pid_cpu_ns,
                    &mut prev_totals,
                    &mut comm_cache,
                    &mut sustained_tracker,
                    elapsed_ns,
                    &config,
                );

                // Print top-N table through tracing at debug level
                let top_n_table = format_top_n_table(&samples, 10);
                debug!(target: "sloth_daemon::sampler", "{}", top_n_table);

                // Evaluate each hot process: classify via AI then apply the policy gate.
                for sample in &samples {
                    if sample.cpu_percent >= config.sampling.cpu_threshold_pct {
                        info!(
                            pid = sample.pid,
                            comm = %sample.comm,
                            cpu_percent = sample.cpu_percent,
                            sustained_secs = sample.sustained_secs,
                            "High CPU process detected"
                        );

                        // Ask the AI classifier (async, advisory; never blocks the loop
                        // longer than the configured timeout).
                        let verdict = classifier.classify(sample).await;
                        info!(
                            pid = sample.pid,
                            comm = %sample.comm,
                            classification = ?verdict.classification,
                            confidence = verdict.confidence,
                            throttle_recommended = verdict.throttle_recommended,
                            reason = %verdict.reason,
                            "AI verdict received"
                        );

                        // Policy gate: all conditions must hold for a throttle.
                        //   1. Sustained above threshold long enough.
                        //   2. Not already throttled.
                        //   3. AI recommends throttle with sufficient confidence.
                        let ai_approves = verdict.throttle_recommended
                            && verdict.confidence >= config.ai.min_confidence;

                        if sample.sustained_secs >= config.sampling.sustained_secs
                            && !cgroup_mgr.is_throttled(sample.pid)
                            && ai_approves
                        {
                            match cgroup_mgr.throttle(sample.pid, &sample.comm, None) {
                                Ok(()) => {
                                    info!(
                                        pid = sample.pid,
                                        comm = %sample.comm,
                                        quota_pct = config.throttle.quota_pct,
                                        dry_run = config.dry_run,
                                        classification = ?verdict.classification,
                                        confidence = verdict.confidence,
                                        "Throttle applied to process"
                                    );
                                }
                                Err(err) => {
                                    warn!(
                                        pid = sample.pid,
                                        comm = %sample.comm,
                                        error = %err,
                                        "Throttle refused or failed"
                                    );
                                }
                            }
                        }
                    }

                    // Release throttled process if CPU has cooled down below release threshold
                    if cgroup_mgr.is_throttled(sample.pid)
                        && sample.cpu_percent < config.throttle.release_below_pct
                    {
                        info!(
                            pid = sample.pid,
                            comm = %sample.comm,
                            cpu_percent = sample.cpu_percent,
                            release_below_pct = config.throttle.release_below_pct,
                            "Process CPU dropped below release threshold; releasing throttle"
                        );
                        let _ = cgroup_mgr.release(sample.pid);
                    }
                }

                // Clean up any throttled processes that have exited
                let active_pids: Vec<u32> = cgroup_mgr.active_records().keys().copied().collect();
                for active_pid in active_pids {
                    if !samples.iter().any(|s| s.pid == active_pid) {
                        debug!(pid = active_pid, "Throttled process is no longer active; releasing");
                        let _ = cgroup_mgr.release(active_pid);
                    }
                }
            }
        }
    }

    cgroup_mgr.release_all();
    info!("Sloth Daemon shutdown complete.");
    ExitCode::SUCCESS
}

