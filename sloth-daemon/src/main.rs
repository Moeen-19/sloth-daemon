    fn test_ebpf_placeholder_detection() {
        // Condition 1: Must detect placeholder and report "eBPF object not built"
        let res = check_ebpf_object(EBPF_PLACEHOLDER_MAGIC);
        assert_eq!(res, Err(EbpfError::NotBuilt));
        assert_eq!(res.unwrap_err().to_string(), "eBPF object not built");

        // Empty bytes must also report not built
        let res_empty = check_ebpf_object(&[]);
        assert_eq!(res_empty, Err(EbpfError::NotBuilt));
        assert_eq!(res_empty.unwrap_err().to_string(), "eBPF object not built");

        // Non-ELF arbitrary bytes must report invalid format
        let res_invalid = check_ebpf_object(b"THIS_IS_NOT_ELF_DATA");
        assert_eq!(res_invalid, Err(EbpfError::InvalidFormat));
        assert_eq!(
            res_invalid.unwrap_err().to_string(),
            "invalid eBPF object format"
        );

        // Valid ELF magic header must pass format validation
        let mut mock_elf = vec![0x7f, b'E', b'L', b'F'];
        mock_elf.extend_from_slice(&[0u8; 60]);
        assert_eq!(check_ebpf_object(&mock_elf), Ok(()));
    }

