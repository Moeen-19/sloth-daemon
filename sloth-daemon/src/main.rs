impl Config {
    /// Loads configuration from an optional file path or returns default settings.
    pub fn load(path: Option<&Path>) -> anyhow::Result<Self> {
        match path {
            Some(p) => {
                let content = fs::read_to_string(p).map_err(|err| {
                    anyhow::anyhow!("failed to read config file {}: {err}", p.display())
                })?;
                let config: Self = toml::from_str(&content).map_err(|err| {
                    anyhow::anyhow!("failed to parse TOML config {}: {err}", p.display())
                })?;
                Ok(config)
            }
            None => Ok(Self::default()),
        }
    }
}

