/// Errors encountered when checking or loading the embedded eBPF object.
#[derive(Debug, thiserror::Error, PartialEq, Eq)]
pub enum EbpfError {
    /// The eBPF object has not yet been compiled.
    #[error("eBPF object not built")]
    NotBuilt,
    /// The embedded bytes do not match expected ELF binary format.
    #[error("invalid eBPF object format")]
    InvalidFormat,
}

/// Checks whether the embedded eBPF object bytes are valid or a placeholder.
pub fn check_ebpf_object(bytes: &[u8]) -> Result<(), EbpfError> {
    if bytes.is_empty() || bytes.starts_with(EBPF_PLACEHOLDER_MAGIC) {
        return Err(EbpfError::NotBuilt);
    }
    // A valid eBPF object is a 64-bit ELF file starting with \x7fELF
    if !bytes.starts_with(b"\x7fELF") {
        return Err(EbpfError::InvalidFormat);
    }
    Ok(())
}

