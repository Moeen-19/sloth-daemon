/// Non-loadable eBPF placeholder magic sequence.
pub const EBPF_PLACEHOLDER_MAGIC: &[u8] = b"SLOTH_EBPF_NOT_BUILT_PLACEHOLDER\0";

/// Embedded eBPF object byte array generated by build.rs.
pub const EBPF_BYTES: &[u8] =
    aya::include_bytes_aligned!(concat!(env!("OUT_DIR"), "/sloth-ebpf.bin"));

