/// Process CPU observation sample collected over a measurement window.
#[derive(Debug, Clone, Serialize, Deserialize, PartialEq)]
pub struct ProcessSample {
    /// Process ID.
    pub pid: u32,
    /// Executable name (comm, max 16 bytes).
    pub comm: String,
    /// CPU percentage used over the window (100.0 = one full core).
    pub cpu_percent: f32,
    /// Measurement window length in seconds.
    pub window_secs: u32,
    /// Number of seconds the process has sustained CPU usage above the threshold.
    pub sustained_secs: u32,
}

/// Action determined by the policy gate.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum ThrottleAction {
    /// No action required.
    None,
    /// Throttle the target PID to the specified percentage of one CPU core.
    Throttle { pid: u32, quota_pct: u8 },
    /// Release the PID back to its original cgroup.
    Release { pid: u32 },
}

